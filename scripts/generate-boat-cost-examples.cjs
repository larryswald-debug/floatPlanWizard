/* Build-time only. CFML serves checked-in HTML without a runtime Node dependency. */
const fs = require('node:fs');
const path = require('node:path');
const engine = require('../assets/js/boat-cost-engine.js');
const money = value => new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD' }).format(value);
const escape = value => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
function render() {
  const keys = ['H','B','I'];
  const scenarios = keys.map(key => engine.example(key));
  const results = scenarios.map(s => engine.calculate(s));
  results.forEach(r => { if (!r.valid || !r.readiness.firstYear) throw new Error('An example is incomplete.'); });
  const f = (input, currency=true) => input.status === 'excluded' ? 'Excluded' : currency ? money(Number(input.value)) : String(input.value);
  const rows = [
    ['Boat price', s=>f(s.purchase.price)],
    ['Down payment in dollars', s=>f(s.purchase.down.input)],
    ['Contract annual interest rate', s=>f(s.purchase.rate,false)+'%'],
    ['Loan term', s=>f(s.purchase.term,false)+' months'],
    ['Purchase tax (cash-paid dollar amount)', s=>f(s.purchase.tax.input)],
    ['Title/documentation fee (cash-paid)', s=>f(s.purchase.fees[0].input)],
    ['Dealer, lender and other purchase fees', ()=> 'Explicitly excluded'],
    ['Annual boat running hours', s=>f(s.operating.fuel.hours,false)+' hours'],
    ['Total GPH for all propulsion engines', s=>f(s.operating.fuel.gph,false)+' GPH'],
    ['Fuel price per US gallon', s=>f(s.operating.fuel.price)],
    ['Generator', ()=> 'Explicitly excluded'],
    ['Annual storage (direct annual amount)', s=>f(s.operating.storage.total)],
    ['Annual insurance', s=>f(s.operating.insurance)],
    ['Annual routine maintenance', s=>f(s.operating.maintenance)],
    ['Annual registration and recurring taxes', s=>f(s.operating.registration)],
    ['Annual seasonal services', s=>f(s.operating.seasonal)],
    ['Other operations, utilities, pump-outs, towing, trailer upkeep, launch fees and subscriptions', ()=> 'Explicitly excluded'],
    ['Survey', s=>f(s.preparation.rows.find(r=>r.type==='survey').input)],
    ['Inspection haul-out', s=>f(s.preparation.rows.find(r=>r.type==='haulout').input)],
    ['Engine inspection', s=>f(s.preparation.rows.find(r=>r.type==='engineInspection').input)],
    ['Immediate repairs', s=>f(s.preparation.rows.find(r=>r.type==='repairs').input)],
    ['Safety equipment', s=>f(s.preparation.rows.find(r=>r.type==='safety').input)],
    ['Delivery, batteries, electronics, initial bottom work and trailer purchase', ()=> 'Explicitly excluded'],
    ['Initial repair reserve', s=>f(s.reserves.initial)],
    ['Annual repair savings', s=>f(s.reserves.annual)],
    ['Resale and selling costs (both horizons)', ()=> 'Excluded; no resale assumed'],
    ['Annual operating expenses', (_,r)=>money(r.operations.annual),'annualOperations'],
    ['Other initial and first-year costs', (_,r)=>money(r.upfront.preparation),'preparation'],
    ['Monthly loan payment', (_,r)=>money(r.loan.payment),'monthlyPayment'],
    ['Estimated monthly boating budget', (_,r)=>money(r.monthly.budget),'monthlyBudget'],
    ['First-year funding target', (_,r)=>money(r.firstYear.funding),'firstYearFunding']
  ];
  return '<!--- Generated by node scripts/generate-boat-cost-examples.cjs; do not hand-edit results. --->\n'+
    '<cfif compareNoCase(getBaseTemplatePath(), getCurrentTemplatePath()) EQ 0>\n'+
    '  <cfheader statuscode="404">\n'+
    '  <cfcontent type="text/plain; charset=utf-8" reset="true">\n'+
    '  <cfoutput>Not Found</cfoutput>\n'+
    '  <cfabort>\n'+
    '</cfif>\n'+
    '<div class="bc-example-actions">'+keys.map((key,i)=>'<button type="button" class="bc-button" data-boat-cost-example="'+key+'">Try '+escape(scenarios[i].label.replace(/^Illustrative /,''))+'</button>').join('')+'</div>\n'+
    '<p>All three are used powerboats, financed purchases, with illustrative assumptions. Physical length, engine count, model year, engine type, water, season and state are unspecified; they do not change these direct storage or total-vessel fuel calculations. Every included amount is illustrative; excluded categories are not assumed free.</p>\n'+
    '<div class="bc-table-scroll" tabindex="0" role="region" aria-label="Worked example assumptions and results"><table class="bc-table"><caption>Complete version 1.0 illustrative input packs and engine-generated results</caption><thead><tr><th scope="col">Assumption or result</th><th scope="col">$25,000 trailer-kept powerboat</th><th scope="col">$50,000 slip-kept cruiser</th><th scope="col">$100,000 larger cruiser</th></tr></thead><tbody>\n'+
    rows.map(([label,get,key])=>'<tr><th scope="row">'+escape(label)+'</th>'+scenarios.map((s,i)=>'<td'+(key?' data-example-output="'+keys[i]+'.'+key+'"':'')+'>'+escape(get(s,results[i]))+'</td>').join('')+'</tr>').join('\n')+
    '\n</tbody></table></div>\n';
}
module.exports = {render};
if (require.main === module) {
  const target = path.join(__dirname,'../boat-loan-calculator/examples.cfm');
  const content = render();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target,'utf8') !== content) { console.error('Static examples differ from the production engine. Regenerate them.'); process.exitCode = 1; }
    else console.log('Static examples match the production engine.');
  } else {
    if (fs.existsSync(target)) {
      const backup = path.join(__dirname,'../.codex-snapshots/boat-cost-20260919/generated-examples-before-update.cfm');
      fs.mkdirSync(path.dirname(backup), { recursive: true });
      if (!fs.existsSync(backup)) fs.copyFileSync(target,backup);
    }
    fs.writeFileSync(target,content);
    console.log('Generated boat-loan-calculator/examples.cfm from the production engine.');
  }
}
