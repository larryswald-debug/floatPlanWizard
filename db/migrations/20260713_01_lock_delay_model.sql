-- Canonical lock-delay timing model.
-- MariaDB 10.5 and MySQL 8 compatible. Idempotently creates and seeds all
-- 68 models used by the FPW route and trip timeline calculations.

CREATE TABLE IF NOT EXISTS lock_delay_model (
  lock_code varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL,
  base_cycle_min int NOT NULL,
  typical_wait_min int NOT NULL,
  best_wait_min int NOT NULL,
  worst_wait_min int NOT NULL,
  notes varchar(512) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  PRIMARY KEY (lock_code),
  CONSTRAINT fk_lock_delay_model_lockcode
    FOREIGN KEY (lock_code) REFERENCES canonical_locks(lock_code)
    ON DELETE RESTRICT
    ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

